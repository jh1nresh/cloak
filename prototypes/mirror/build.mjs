import {build} from 'esbuild';
import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {verifyModel} from './download-model.mjs';
const root = new URL('./', import.meta.url);
const output = new URL('dist/', root);
const baseline = new URL('../../', root);
await verifyModel();
await mkdir(output, {recursive:true});
const catalog = JSON.parse(await readFile(new URL('prototypes/wardrobe/catalog.json', baseline), 'utf8'));
const template = await readFile(new URL('src/index.html', root), 'utf8');
if(template.split('__CATALOG__').length!==2)throw Error('Expected one catalog slot');
await writeFile(new URL('index.html', output), template.replace('__CATALOG__', () => JSON.stringify(catalog).replaceAll('<','\\u003c')));
await cp(new URL('public/prototypes/wardrobe/wardrobe-assets/', baseline), new URL('wardrobe-assets/', output), {recursive:true});
await cp(new URL('node_modules/@mediapipe/tasks-vision/wasm/', root), new URL('wasm/', output), {recursive:true});
await cp(new URL('models/', root), new URL('models/', output), {recursive:true});
await cp(new URL('src/style.css', root), new URL('style.css', output));
await build({entryPoints:[fileURLToPath(new URL('src/app.ts',root)),fileURLToPath(new URL('src/hand-worker.ts',root))],outdir:fileURLToPath(output),bundle:true,format:'esm',target:'es2022',minify:true,legalComments:'inline'});
console.log('Built local mirror prototype');
